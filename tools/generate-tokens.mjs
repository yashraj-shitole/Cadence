#!/usr/bin/env node
// Generates the Kotlin token module from the design handoff.
//   node tools/generate-tokens.mjs
// Inputs  (cadence-handoff/design-system): tokens.json, palettes.json, components/bundle.css (palette overrides, incl. high-contrast values)
// Output  app/src/main/java/com/yashraj/cadence/ui/theme/GeneratedTokens.kt
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ds = join(root, 'cadence-handoff', 'design-system');
const tokens = JSON.parse(readFileSync(join(ds, 'tokens.json'), 'utf8'));
const palettes = JSON.parse(readFileSync(join(ds, 'palettes.json'), 'utf8'));
const bundle = readFileSync(join(ds, 'components', 'bundle.css'), 'utf8');
const outFile = join(root, 'app', 'src', 'main', 'java', 'com', 'yashraj', 'cadence', 'ui', 'theme', 'GeneratedTokens.kt');

const THEMES = ['light', 'dark', 'hc-light', 'hc-dark'];
const themeEnum = { light: 'Light', dark: 'Dark', 'hc-light': 'HcLight', 'hc-dark': 'HcDark' };
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

// ---------- colour parsing ----------
function color(v) {
  v = v.trim();
  let m = /^#([0-9a-f]{3})$/i.exec(v);
  if (m) v = '#' + [...m[1]].map((c) => c + c).join('');
  m = /^#([0-9a-f]{6})$/i.exec(v);
  if (m) return `Color(0xFF${m[1].toUpperCase()})`;
  m = /^rgba?\(([^)]+)\)$/.exec(v);
  if (m) {
    const p = m[1].split(',').map((x) => x.trim());
    const a = p[3] === undefined ? 255 : Math.round(parseFloat(p[3]) * 255);
    const h = (n) => Math.round(parseFloat(n)).toString(16).padStart(2, '0').toUpperCase();
    return `Color(0x${a.toString(16).padStart(2, '0').toUpperCase()}${h(p[0])}${h(p[1])}${h(p[2])})`;
  }
  throw new Error('Unparsed colour: ' + v);
}

// ---------- shadow parsing ("inset 0 1px 0 rgba(...), 0 10px 28px rgba(...)") ----------
function splitTop(s) {
  const out = []; let depth = 0, cur = '';
  for (const ch of s) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}
function shadowList(v) {
  if (v === 'none') return '$$SHADOWS_NONE';
  const layers = splitTop(v).map((layer) => {
    const inset = layer.startsWith('inset');
    const rest = inset ? layer.slice(5).trim() : layer;
    const ci = rest.search(/(rgba?\(|#)/);
    const nums = rest.slice(0, ci).trim().split(/\s+/).map((n) => parseFloat(n));
    const [x, y, blur = 0, spread = 0] = nums;
    return `ShadowLayer(${inset}, ${x}f, ${y}f, ${blur}f, ${spread}f, ${color(rest.slice(ci))})`;
  });
  return `listOf(${layers.join(', ')})`;
}

const px = (v) => parseFloat(v);
const ms = (v) => parseInt(v, 10);
const lines = [];
const w = (s = '') => lines.push(s);

w('// GENERATED by tools/generate-tokens.mjs from cadence-handoff/design-system. Do not edit by hand.');
w('@file:Suppress("unused", "MagicNumber")');
w();
w('package com.yashraj.cadence.ui.theme');
w();
w('import androidx.compose.animation.core.CubicBezierEasing');
w('import androidx.compose.ui.graphics.Color');
w('import androidx.compose.ui.unit.dp');
w();
w('enum class ThemeId { Light, Dark, HcLight, HcDark }');
w();
w('/** One layer of a CSS-style box shadow. Inset layers are drawn inside the tile. */');
w('class ShadowLayer(val inset: Boolean, val x: Float, val y: Float, val blur: Float, val spread: Float, val color: Color)');
w();
w('private val NoShadow = emptyList<ShadowLayer>()');
w();

// ---------- base colours ----------
const colorTokens = tokens.color.tokens;
const colorNames = colorTokens.map((t) => t.name).filter((n) => n !== 'focus-ring');
w('/** Theme colours that do not depend on the chosen palette. */');
w('class BaseColors(');
colorNames.forEach((n, i) => w(`    val ${camel(n)}: Color${i < colorNames.length - 1 ? ',' : ''}`));
w(')');
w();
w('val BaseThemes: Map<ThemeId, BaseColors> = mapOf(');
THEMES.forEach((th, ti) => {
  w(`    ThemeId.${themeEnum[th]} to BaseColors(`);
  colorNames.forEach((n, i) => {
    const t = colorTokens.find((x) => x.name === n);
    w(`        ${camel(n)} = ${color(t.value[th])}${i < colorNames.length - 1 ? ',' : ''}`);
  });
  w(`    )${ti < THEMES.length - 1 ? ',' : ''}`);
});
w(')');
w();

// ---------- shadows ----------
const shadowTokens = tokens.shadow.tokens;
w('/** Shadow recipes per theme: glass bevel, floating bevel, accent glow, control thumb. */');
w('class ShadowSet(val glass: List<ShadowLayer>, val float: List<ShadowLayer>, val accent: List<ShadowLayer>, val thumb: List<ShadowLayer>)');
w();
w('val ShadowThemes: Map<ThemeId, ShadowSet> = mapOf(');
THEMES.forEach((th, ti) => {
  const get = (name) => shadowList(shadowTokens.find((t) => t.name === name).value[th]).replace('$$SHADOWS_NONE', 'NoShadow');
  w(`    ThemeId.${themeEnum[th]} to ShadowSet(`);
  w(`        glass = ${get('shadow-glass')},`);
  w(`        float = ${get('shadow-float')},`);
  w(`        accent = ${get('shadow-accent')},`);
  w(`        thumb = ${get('shadow-thumb')}`);
  w(`    )${ti < THEMES.length - 1 ? ',' : ''}`);
});
w(')');
w();

// ---------- palettes (values come from the palette overrides in bundle.css, which include the high-contrast figures) ----------
const ruleRe = /\[data-palette="([a-z]+)"\]\[data-theme="([a-z-]+)"\]\{([^}]*)\}/g;
const overrides = {};
for (const m of bundle.matchAll(ruleRe)) {
  const [, pal, th, body] = m;
  const props = {};
  for (const d of body.split(';')) {
    const i = d.indexOf(':');
    if (i > 0) props[d.slice(0, i).trim().replace(/^--/, '')] = d.slice(i + 1).trim();
  }
  (overrides[pal] ||= {})[th] = props;
}
w('/** What a colour palette sets. Everything else stays fixed across palettes. */');
w('class PaletteColors(');
w('    val accent: Color,');
w('    val onAccent: Color,');
w('    val accentSoft: Color,');
w('    val rest: Color,');
w('    val restSoft: Color,');
w('    val glow1: Color?,');
w('    val glow2: Color?,');
w('    val glow3: Color?,');
w('    /** Replaces the base accent shadow when non-null (light theme). */');
w('    val accentShadow: List<ShadowLayer>?');
w(')');
w();
w('class PaletteDef(val id: String, val displayName: String, val note: String, val colors: Map<ThemeId, PaletteColors>)');
w();
w(`const val DefaultPaletteId = "${palettes.default}"`);
w();
w('val Palettes: List<PaletteDef> = listOf(');
palettes.palettes.forEach((p, pi) => {
  w(`    PaletteDef("${p.id}", "${p.name}", ${JSON.stringify(p.note)}, mapOf(`);
  THEMES.forEach((th, ti) => {
    const o = overrides[p.id]?.[th];
    if (!o) throw new Error(`No override for ${p.id}/${th}`);
    const opt = (k) => (o[k] ? color(o[k]) : 'null');
    const shadow = o['shadow-accent'] ? shadowList(o['shadow-accent']).replace('$$SHADOWS_NONE', 'NoShadow') : 'null';
    w(`        ThemeId.${themeEnum[th]} to PaletteColors(`);
    w(`            accent = ${color(o.accent)}, onAccent = ${color(o['on-accent'])}, accentSoft = ${color(o['accent-soft'])},`);
    w(`            rest = ${color(o.rest)}, restSoft = ${color(o['rest-soft'])},`);
    w(`            glow1 = ${opt('glow-1')}, glow2 = ${opt('glow-2')}, glow3 = ${opt('glow-3')},`);
    w(`            accentShadow = ${shadow}`);
    w(`        )${ti < THEMES.length - 1 ? ',' : ''}`);
  });
  w(`    ))${pi < palettes.palettes.length - 1 ? ',' : ''}`);
});
w(')');
w();

// ---------- spacing, radius, size, blur ----------
const group = (objName, list, strip, fmt, doc) => {
  w(`/** ${doc} */`);
  w(`object ${objName} {`);
  list.forEach((t) => w(`    ${fmt(t)} // ${t.usage.replace(/`/g, '')}`));
  w('}');
  w();
};
group('Space', tokens.spacing.tokens, 'space-', (t) => `val s${t.name.replace('space-', '')} = ${px(t.value)}.dp`, 'Spacing scale.');
group('Radius', tokens.radius.tokens, 'radius-', (t) => `val ${camel(t.name.replace('radius-', ''))} = ${px(t.value)}.dp`, 'Corner radii.');
group('Sizes', tokens.size.tokens, '', (t) => `val ${camel(t.name)} = ${px(t.value)}.dp`, 'Fixed sizes.');
group('Blur', tokens.blur.tokens, 'blur-', (t) => `val ${camel(t.name.replace('blur-', ''))} = ${px(t.value)}.dp`, 'Blur radii.');

// ---------- duration, easing ----------
group('Dur', tokens.duration.tokens, 'duration-', (t) => `const val ${camel(t.name.replace('duration-', ''))} = ${ms(t.value)}`, 'Durations in milliseconds.');
w('/** Easing curves. */');
w('object Ease {');
tokens.easing.tokens.forEach((t) => {
  const nums = /cubic-bezier\(([^)]+)\)/.exec(t.value)[1].split(',').map((n) => parseFloat(n.trim()));
  w(`    val ${camel(t.name)} = CubicBezierEasing(${nums.map((n) => n + 'f').join(', ')}) // ${t.usage.replace(/`/g, '')}`);
});
w('}');
w();

// ---------- scales, haptics ----------
w('/** Press scales and the four Motion stops. */');
w('object Scales {');
tokens.scale.tokens.forEach((t) => w(`    const val ${camel(t.name)} = ${parseFloat(t.value)}f // ${t.usage.replace(/`/g, '')}`));
w('}');
w();
w('/** Haptic event amplitudes and the four Haptics stops. */');
w('object HapticTokens {');
tokens.haptic.tokens.forEach((t) => w(`    const val ${camel(t.name.replace(/^haptic-/, ''))} = ${parseFloat(t.value)}f // ${t.usage.replace(/`/g, '')}`));
w('}');
w();

// ---------- type ----------
w('/** A type style from tokens.json: sizes are sp, letterSpacing is em. */');
w('class TypeSpec(val display: Boolean, val size: Float, val lineHeight: Float, val weight: Int, val letterSpacing: Float)');
w();
w('object TypeSpecs {');
for (const g of tokens.type.groups) {
  for (const s of g.styles) {
    const ls = s.letterSpacing ? parseFloat(s.letterSpacing) : 0;
    w(`    val ${camel(s.name)} = TypeSpec(${g.family === 'display'}, ${px(s.fontSize)}f, ${px(s.lineHeight)}f, ${s.fontWeight}, ${ls}f) // ${s.usage.replace(/`/g, '')}`);
  }
}
w('}');
w();

writeFileSync(outFile, lines.join('\n'));
console.log('Wrote', outFile);
